"""Targeted exact diagnostic: bank cost of weak main improvements in a full SPE.

Each complete ordered-history strategy is independently generated by exact
backward induction. No count-based continuation selector is imposed. NumPy only
stores the full 9-ary ordered tree efficiently; all comparisons are integers on
the denominator lcm(1,...,m). This is a finite candidate diagnostic, not proof.
"""
from fractions import Fraction
from itertools import product
from math import lcm
import json
import numpy as np


def probe(m, wm, wb, seed):
    den = lcm(*range(1, m + 1))
    rng = np.random.default_rng(seed)
    n = 9**m
    raw = np.arange(n, dtype=np.int64)
    mc = np.zeros((n, 3), dtype=np.int16)
    bc = np.zeros((n, 3), dtype=np.int16)
    for _ in range(m):
        digit = raw % 9
        raw //= 9
        for a in range(3):
            mc[:, a] += digit // 3 == a
            bc[:, a] += digit % 3 == a
    tuples = np.concatenate((mc, bc), axis=1)
    states, leaf_ids = np.unique(tuples, axis=0, return_inverse=True)
    um = np.zeros((len(states), 3), dtype=np.int64)
    ub = np.zeros_like(um)
    for a in range(3):
        nz = states[:, a] > 0
        um[nz, a] = np.asarray(wm)[a] * den // states[nz, a]
        nz = states[:, a + 3] > 0
        ub[nz, a] = np.asarray(wb)[a] * den // states[nz, a + 3]
    joint = um[:, np.arange(9) // 3] + ub[:, np.arange(9) % 3]
    terminals = [None] * (m + 1)
    actions = [None] * m
    terminals[m] = leaf_ids
    for depth in range(m - 1, -1, -1):
        child = terminals[depth + 1].reshape(-1, 9)
        score = joint[child, np.arange(9)]
        best = score.max(axis=1)
        # Independent ordered-history tie choices, exact best-response support.
        jitter = rng.random(score.shape)
        jitter[score != best[:, None]] = -1
        chosen = jitter.argmax(axis=1)
        actions[depth] = chosen
        terminals[depth] = child[np.arange(len(child)), chosen]
    value = np.zeros(n, dtype=np.int64)
    choices = [None] * m
    for depth in range(m - 1, -1, -1):
        child = terminals[depth + 1].reshape(-1, 9)
        child_value = value.reshape(-1, 9)
        actual = actions[depth]
        bank = actual % 3
        main = actual // 3
        root_state = terminals[depth]
        current_bank = ub[root_state, bank]
        current_main = um[root_state, main]
        candidate = 3 * np.arange(3)[None, :] + bank[:, None]
        rows = np.arange(len(child))[:, None]
        child_state = child[rows, candidate]
        bank_cost = current_bank[:, None] - ub[child_state, bank[:, None]]
        main_gain = um[child_state, np.arange(3)[None, :]] - current_main[:, None]
        total = bank_cost + child_value[rows, candidate]
        total[main_gain < 0] = -10**12
        take = total.argmax(axis=1)
        value = total[np.arange(len(total)), take]
        choices[depth] = candidate[np.arange(len(candidate)), take]
    rid = int(terminals[0][0])
    root_wb = sum(wb[a] for a in range(3) if states[rid, a + 3])
    path = []
    index = 0
    for depth in range(m):
        actual = int(actions[depth][index])
        chosen = int(choices[depth][index])
        child_index = 9 * index + chosen
        sid = int(terminals[depth][index])
        tid = int(terminals[depth + 1][child_index])
        bank = actual % 3
        path.append({
            "actual": [actual // 3, bank],
            "explore": [chosen // 3, chosen % 3],
            "main_gain": str(Fraction(int(um[tid, chosen // 3] - um[sid, actual // 3]), den)),
            "bank_cost": str(Fraction(int(ub[sid, bank] - ub[tid, bank]), den)),
            "actual_final_marginals": states[sid].tolist(),
            "explore_final_marginals": states[tid].tolist(),
        })
        index = child_index
    return {
        "m": m, "main_weights": wm, "bank_weights": wb, "seed": seed,
        "root_bank_welfare": root_wb,
        "max_weak_main_path_bank_cost": str(Fraction(int(value[0]), den)),
        "ratio": str(Fraction(int(value[0]), den * root_wb)),
        "path": path,
        "ordered_nonterminal_nodes": sum(9**d for d in range(m)),
    }


if __name__ == "__main__":
    cases = [
        (4, [5, 3, 6], [1, 3, 1]),
        (5, [8, 5, 15], [1, 4, 1]),
        (6, [11, 6, 24], [1, 5, 1]),
        (6, [1, 2, 5], [1, 2, 5]),
        (6, [3, 4, 7], [5, 4, 3]),
    ]
    results = [probe(m, wm, wb, seed) for m, wm, wb in cases for seed in range(3)]
    summary = {
        "scope": "15 exact full ordered-history SPEs; 3x3 singleton Cartesian catalogs",
        "candidate": "sum bank loss along a weakly main-improving exploration <= root bank welfare",
        "is_general_proof": False,
        "max_result": max(results, key=lambda r: Fraction(r["ratio"])),
        "results": results,
    }
    print(json.dumps(summary, indent=2))

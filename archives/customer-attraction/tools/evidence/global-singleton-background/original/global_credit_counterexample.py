"""Exact unit-customer audit: arbitrary legal-background GLOBAL is false.

The six strategic topics are extended by one singleton background topic for
each occupied customer. This audits all 40 first actions and 40 last actions,
so the background is generated by genuine common-catalog actions.
"""
from fractions import Fraction as F
from pathlib import Path
import json

ROWS=[(1,1,10),(2,1,12),(4,0,5),(8,0,5),(20,0,2),(24,0,2),(36,0,2),(40,0,2),(49,1,6),(50,1,6)]

def run():
 customers=[]; next_singleton=6
 for mask,b,n in ROWS:
  for _ in range(n):
   topics={a for a in range(6) if mask&(1<<a)}
   if b:
    topics.add(next_singleton); next_singleton+=1
   customers.append((topics,b))
 q=next_singleton
 assert q==40 and len(customers)==52
 prefix=list(range(6,q))
 assert all(sum(a in topics for a in prefix)==b for topics,b in customers)
 def payoff(a,path):
  return sum((F(1,b+sum(c in topics for c in path)) for topics,b in customers if a in topics),F(0))
 replies=[1,4,4,4,5,4]
 table=[]
 for a in range(q):
  row=[payoff(c,[a,c]) for c in range(q)]
  if a>=6: replies.append(max(range(q),key=lambda c:row[c]))
  assert row[replies[a]]==max(row),(a,replies[a],row)
  table.append(row)
 root=[payoff(a,[a,replies[a]]) for a in range(q)]
 assert root[:6]==[F(8)]*6
 assert max(root[6:])<=F(1,2)
 assert root[0]==max(root)
 actual=[0,1]
 actual_u=[payoff(a,actual) for a in actual]
 assert actual_u==[F(8),F(9)]
 delta=sum(b==0 and any(a in topics for a in actual) for topics,b in customers)
 assert delta==0
 fresh_opt=0; optimal_pairs=[]
 for a in range(q):
  for c in range(a,q):
   coverage=sum(b==0 and (a in topics or c in topics) for topics,b in customers)
   if coverage>fresh_opt: fresh_opt=coverage; optimal_pairs=[(a,c)]
   elif coverage==fresh_opt: optimal_pairs.append((a,c))
 assert fresh_opt==18 and (2,3) in optimal_pairs
 assert sum(actual_u)+delta==17<fresh_opt
 result={'status':'exact complete fixed-background tail SPE counterexample','remaining_players':2,'catalog_topics':q,'total_unit_customers':len(customers),'legal_prefix':prefix,'rows':ROWS,'replies':replies,'last_payoff_table':[[str(v) for v in row] for row in table],'first_payoff_values':[str(v) for v in root],'actual_utilities':[str(v) for v in actual_u],'P':17,'actual_new_coverage':delta,'freshOPT_2':fresh_opt,'fresh_optimal_pairs':optimal_pairs,'claim_refuted':'P+Delta >= freshOPT at every arbitrary legal background','not_refuted':['zero-background half coverage','same inequality restricted to prefixes reached on a root SPE path','background half profit 2P >= F_k(b)']}
 path=Path(__file__).with_name('global_credit_counterexample_audit.json'); path.write_text(json.dumps(result,indent=2))
 print(json.dumps({k:v for k,v in result.items() if k!='last_payoff_table'},indent=2))

if __name__=='__main__': run()

#!/usr/bin/env python3
"""Exact finite audit for the high-degree / minimum-user-share candidate.

Run from repository root: python3 tests/audits/weighted_congestion/high_degree_share/verify.py
Default recomputes and compares frozen evidence; --generate NEW_PATH refuses overwrite.
Standard library only. Fixed boundary inputs are literal below; pseudorandom
inputs are generated by random.Random(17), never by system randomness.
No numerical root, floating inequality, or ratio of zero costs is used.
"""

from __future__ import annotations

import argparse
import hashlib
import platform
from fractions import Fraction as F
from itertools import product
import json
from pathlib import Path
from random import Random


def game(weights, strategies, coefficients, k, name):
    return dict(weights=tuple(map(F, weights)),
                strategies=tuple(tuple(frozenset(s) for s in ss)
                                 for ss in strategies),
                coefficients=tuple({j: F(a) for j, a in c.items()}
                                   for c in coefficients), k=k, name=name)


def audit(g):
    w, ss, cc = g['weights'], g['strategies'], g['coefficients']
    n, m, k = len(w), len(cc), g['k']
    assert n > 0 and m > 0 and k >= 1
    assert all(z > 0 for z in w)
    assert all(choices for choices in ss)
    assert all(a >= 0 and (j == 0 or j >= k)
               for c in cc for j, a in c.items() if a)
    users = [{i for i in range(n) if any(e in s for s in ss[i])}
             for e in range(m)]
    local = []
    for e, u in enumerate(users):
        js = [j for j, a in cc[e].items() if j > 0 and a > 0]
        if not u or not js:
            local.append(F(1))
        else:
            total = sum((w[i] for i in u), F(0))
            q = min(w[i]/total for i in u)
            local.append(1-(1-q)**min(js))
    lam = min(local)
    assert 0 < lam <= 1

    def evaluate(s):
        x = [sum((w[i] for i in range(n) if e in s[i]), F(0))
             for e in range(m)]
        counts = [sum(e in t for t in s) for e in range(m)]
        fees = [sum((a*x[e]**j for j, a in cc[e].items()), F(0))
                for e in range(m)]
        costs = [sum((fees[e] for e in s[i]), F(0)) for i in range(n)]
        parts = [cc[e].get(0, F(0))*counts[e]
                 + sum((a*x[e]**j for j, a in cc[e].items() if j > 0), F(0))
                 for e in range(m)]
        return costs, sum(parts, F(0)), parts, fees

    data = {s: evaluate(s) for s in product(*ss)}
    least = min(v[1] for v in data.values())
    checks = resource_checks = zero_deviation_checks = retained_checks = 0
    minimizers = sum(v[1] == least for v in data.values())
    for s, (old, p, old_parts, old_fees) in data.items():
        for i in range(n):
            for t in ss[i]:
                z = list(s)
                z[i] = t
                z = tuple(z)
                new, pp, new_parts, new_fees = data[z]
                removed, added, common = s[i]-t, t-s[i], s[i] & t
                for e in removed:
                    assert old_parts[e]-new_parts[e] >= local[e]*old_fees[e]
                    resource_checks += 1
                for e in added:
                    assert new_parts[e]-old_parts[e] <= new_fees[e]
                    resource_checks += 1
                for e in common:
                    assert new_parts[e] == old_parts[e]
                    assert new_fees[e] == old_fees[e]
                    resource_checks += 1
                retained = sum((old_fees[e] for e in common), F(0))
                assert pp-p <= new[i]-lam*old[i]-(1-lam)*retained
                if p == least:
                    assert lam*old[i] <= new[i]
                if lam*old[i] > new[i]:
                    assert pp < p
                checks += 1
                zero_deviation_checks += new[i] == 0
                retained_checks += bool(common)
    return dict(name=g['name'], players=n, resources=m, k=k,
                profiles=len(data), local_lambdas=list(map(str, local)),
                alpha=str(1/lam), minimum_states=minimizers, move_checks=checks,
                resource_checks=resource_checks, zero_deviation_checks=zero_deviation_checks,
                retained_resource_moves=retained_checks)


def inputs():
    yield game([1], [[[], [0]]], [{0: 0}], 1, 'all-zero-and-empty')
    yield game([2, 3], [[[0], []], [[0], []]], [{0: 7}, {0: 3, 5: 9}], 3,
               'constants-and-unusable-positive-resource')
    yield game([1, 5], [[[0], []], [[1], []]], [{3: 2}, {0: 1, 4: 3}], 3,
               'singleton-resources-q-one')
    yield game([F(1, 3), F(2, 5)],
               [[[0, 1], [0], []], [[0, 2], [0], []]],
               [{0: 2, 5: 3}, {7: 4}, {5: 6, 6: 1}], 5,
               'retained-resource-heterogeneous-rational')
    # Constant-cost choice; only the exact minimum is a potential minimum.
    yield game([1], [[[0], [1]]], [{0: 1}, {0: 2}], 1,
               'constant-cost-choice')
    rng = Random(17)
    for n in range(1, 5):
        for trial in range(24):
            weights = [F(rng.randint(1, 9), rng.randint(1, 6)) for _ in range(n)]
            ss = []
            for _ in range(n):
                # Sorted canonical order makes the actual input independent
                # of Python hash randomization.
                choices = {tuple(e for e in range(3) if rng.randrange(2))
                           for _ in range(4)}
                ss.append([list(t) for t in sorted(choices)] or [[]])
            k = rng.randint(1, 5)
            cc = []
            for _ in range(3):
                c = {0: rng.randint(0, 3)}
                c.update({j: rng.randint(0, 3) for j in range(k, k+3)})
                cc.append(c)
            yield game(weights, ss, cc, k, f'seed17-n{n}-trial{trial}')


def endpoint_checks():
    # The strict necessary share relation is derived algebraically, so
    # rational d=1 tests check both equality and the two sides exactly.
    for alpha in (F(2), F(3), F(11, 7)):
        threshold = 1/alpha
        for q in (threshold/2, threshold, (1+threshold)/2):
            bound = 1/q
            assert (bound > alpha) == (q < threshold)
            assert (bound <= alpha) == (q >= threshold)
    # Invert the symbolic factor by exact arithmetic, with q=1/10.
    examples = []
    for k in (1, 2, 10, 100):
        q = F(1, 10)
        alpha = 1/(1-(1-q)**k)
        assert 1-1/alpha == (1-q)**k
        examples.append(dict(q=str(q), k=k, alpha=str(alpha)))
    return examples


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--generate', type=Path)
    args = parser.parse_args()
    cases = [audit(g) for g in inputs()]
    report = dict(status='passed', arithmetic='fractions.Fraction only', seed=17,
                  random_inputs='n=1..4, 24 games each, 3 resources, max 4 strategies/player',
                  exact_scope='finite moves and all global potential minimizers only',
                  general_proof='research/current/weighted_congestion/high_degree_share.md',
                  python_version=platform.python_version(),
                  code_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  no_external_dependencies=True, cases=cases,
                  totals={key: sum(c[key] for c in cases) for key in
                          ('profiles', 'minimum_states', 'move_checks', 'resource_checks',
                           'zero_deviation_checks', 'retained_resource_moves')},
                  factor_inversion_examples=endpoint_checks())
    text = json.dumps(report, ensure_ascii=False, indent=2)+'\n'
    if args.generate:
        with args.generate.open('x', encoding='utf-8') as stream:
            stream.write(text)
    else:
        frozen = Path(__file__).resolve().parents[4] / 'evidence/runs/weighted_congestion/high_degree_share/verification.json'
        assert json.loads(frozen.read_text()) == report, 'frozen record mismatch'
    print(json.dumps({k: report[k] for k in ('status', 'seed', 'totals')}, ensure_ascii=False))


if __name__ == '__main__':
    main()
